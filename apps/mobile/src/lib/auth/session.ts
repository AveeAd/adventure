// For an already signed-in user attaching Apple as a second identity - see
// AuthService.linkAppleIdentity for why the private-relay email case needs
// this instead of relying on auto-link.
export async function linkAppleIdentity(identityToken: string): Promise<void> {
  await authPost('/auth/link/apple', { identityToken });
}

export async function fetchCurrentUser(): Promise<CurrentUser | null> {
  const authenticated = tokenStore.get() ? true : await restoreSession();
  if (!authenticated) {
    return null;
  }
  const res = await fetch(apiUrl('/auth/me'), {
    headers: { Authorization: `Bearer ${tokenStore.get()}`, [CLIENT_VERSION_HEADER]: CLIENT_VERSION },
  });
  await checkUpgradeRequired(res);
  if (!res.ok) {
    return null;
  }
  return res.json();
}

// DELETE /users/me (App Store Guideline 5.1.1(v), MOBILE_PLAN.md Phase 7) -
// server soft-deletes + anonymizes and revokes the refresh token itself, so
// this only needs to clear the client-side copies, same as logout below.
export async function deleteAccount(): Promise<void> {
  await authDelete('/users/me');
  tokenStore.set(null);
  await secureStorage.clearRefreshToken();
}

export async function logout(): Promise<void> {
  const refreshToken = await secureStorage.getRefreshToken();
  await fetch(apiUrl('/auth/logout'), {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ refreshToken }),
  }).catch(() => undefined);
  tokenStore.set(null);
  await secureStorage.clearRefreshToken();
}
